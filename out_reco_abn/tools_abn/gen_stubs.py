#!/usr/bin/env python3
"""gen_stubs.py - (re)generate out_reco_abn/abn_hook_stubs.cpp from a REAL link failure.

HISTORY / STATUS
----------------
Original leg (2026-07-30 evening): the host hook layer named reco_normal addresses, so 75
`__imp__sub_88XXXXXX` twins did not exist in out_reco_abn and the link failed.  This script emitted
75 loud weak no-op stubs so futari_merged_v154hi.exe could link at all.

Hook-revival leg (2026-07-30 night, _tmpscripts/abn_hooks_revive_notes.md): out_reco_abn/
abn_symbol_map.h now renames every shifted host hook onto its +8 twin, so ALL of those __imp__
references resolve into the real generated bodies.  `ABN_NOSTUBS=1 bash _tmpscripts/build_win_abn.sh`
now reports **0 distinct** unresolved __imp__ symbols and links clean.  The generated stub TU is
therefore EMPTY - by design, and that emptiness is the deliverable.

Usage
-----
    ABN_NOSTUBS=1 bash _tmpscripts/build_win_abn.sh     # link without stubs; writes obj_win_abn/link.err
    python out_reco_abn/tools_abn/gen_stubs.py          # reads that link.err, rewrites the stub TU

If the census is empty the TU is emitted with zero stubs and a header saying so.  If it is NOT
empty, that is a REGRESSION in the symbol map (a hook the map missed, or a genuinely absent
function) - the printed list is the work item, and adding a stub only papers over it.

Trap worth keeping: lld-link prints these as `undefined symbol: __declspec(dllimport) _sub_88XXXXXX`,
NOT as `__imp__sub_88XXXXXX`.  Grepping for `__imp__` in link.err finds nothing and reads as a false
all-clear.  It also truncates at ~20 errors without /errorlimit:0.
"""
import os, re, sys, collections

HERE = os.path.dirname(os.path.abspath(__file__))
ABN = os.path.dirname(HERE)
XRW = os.path.dirname(ABN)
SPLIT_LO = 0x880DEF88

errpath = sys.argv[1] if len(sys.argv) > 1 else os.path.join(XRW, 'obj_win_abn', 'link.err')
txt = open(errpath, encoding='utf-8', errors='replace').read() if os.path.exists(errpath) else ''
unres = sorted(set('sub_' + m for m in re.findall(r'dllimport\) _sub_(88[0-9A-Fa-f]{6})', txt)))

# how each one is referenced, so a stub comment can say what it was for
src = {}
DEF = re.compile(r'(PPC_FUNC|PPC_FUNC_IMPL|[A-Z][A-Za-z0-9_]*(?:_WRAP|_TRACE|_WATCH_WRAP))'
                 r'\((?:__imp__)?(sub_88[0-9A-Fa-f]{6})\)')
# DECOMP_DIR: the readable-decomp tree moved to the sibling repo projects/futari_decomp
# (2026-08-14 split); env override matches the build scripts' DECOMP_DIR.
DECOMP = os.environ.get('DECOMP_DIR') or os.path.join(XRW, '..', 'futari_decomp', 'decomp')
for p in [os.path.join(XRW, 'out_reco/merged/merged_game.cpp'),   # was merged_xex.cpp pre-L2 split
          os.path.join(XRW, 'out_reco/merged/merged_bridge.cpp'),
          os.path.join(XRW, 'out_reco/merged/merged_shell.cpp'),
          os.path.join(DECOMP, 'game/game_entry_msgs.cpp'),
          os.path.join(DECOMP, 'game/nvk_game_hooks.cpp'),
          os.path.join(DECOMP, 'shell/nvk.cpp')]:
    if not os.path.exists(p):
        continue
    for line in open(p, encoding='utf-8', errors='replace'):
        s = line.lstrip()
        if s.startswith(('//', '*', '#define', '/*')):
            continue
        m = DEF.match(s)
        if m:
            src.setdefault(m.group(2), set()).add(m.group(1))
DIRECT = [s for s in unres if s not in src]

EMPTY_HDR = '''// abn_hook_stubs.cpp - GENERATED by out_reco_abn/tools_abn/gen_stubs.py.  Do not hand-edit.
//
// ZERO STUBS.  This is the intended end state.
//
// Until the hook-revival leg (2026-07-30 night) this file carried 75 loud weak no-op definitions
// of `__imp__sub_88XXXXXX` symbols that exist in reco_normal but not in reco_abnormal, purely so
// futari_merged_v154hi.exe could link.  Every one of those hooks was DEAD: reco_abnormal's
// PPCFuncMappings has no slot at the reco_normal address, so the enclosing `sub_88XXXXXX` override
// was unreachable and the stub was never even entered.
//
// out_reco_abn/abn_symbol_map.h now renames each shifted host hook onto its +8 twin
// (out_reco_abn/tools_abn/gen_symbol_map.py, from _tmpscripts/abn_hook_census.json + the split
// rule), so the `__imp__` references resolve into the REAL generated reco_abnormal bodies and the
// overrides sit in PPCFuncMappings where the guest actually calls them.  Nothing is left to stub:
//
//     ABN_NOSTUBS=1 bash _tmpscripts/build_win_abn.sh   ->   0 distinct unresolved __imp__, LINK_OK
//
// If this file ever regains stubs, that is a REGRESSION in the symbol map, not a fix.
// Re-derive with:  ABN_NOSTUBS=1 bash _tmpscripts/build_win_abn.sh
//                  python out_reco_abn/tools_abn/gen_stubs.py
'''

if not unres:
    out = EMPTY_HDR + '\n// (intentionally no code)\n'
    open(os.path.join(ABN, 'abn_hook_stubs.cpp'), 'w', encoding='utf-8', newline='\n').write(out)
    print('wrote out_reco_abn/abn_hook_stubs.cpp: 0 stubs (link.err = %s)' %
          (errpath if txt else 'absent/empty'))
    sys.exit(0)

H = '''// abn_hook_stubs.cpp - GENERATED by out_reco_abn/tools_abn/gen_stubs.py.  Do not hand-edit.
//
// ⚠ REGRESSION: %d host `__imp__sub_88XXXXXX` references still do not resolve after
// out_reco_abn/abn_symbol_map.h was applied.  Expected count is ZERO.  Each entry below is either
// a hook the symbol map failed to rename or a function genuinely absent from reco_abnormal.  A
// weak no-op here only hides it - fix the map (gen_symbol_map.py) or record real decomp debt.
//
// A stub that never fires does NOT mean the hook is fine: if the address has no PPCFuncMappings
// slot the enclosing override is unreachable and the stub is never entered.  Silence != ported.
// %d of these are called DIRECTLY rather than through a PPC_FUNC wrapper (%s) - for those a no-op
// really does replace behaviour and they WILL fire.
'''

body = ['#include "ppc_recomp_shared.h"', '#include <cstdio>', '#include <atomic>', '',
        'static std::atomic<int> g_abn_stub_fired{0};', '',
        '#define ABN_STUB(NAME, TWIN)                                                          \\',
        '    static std::atomic<bool> once_##NAME{false};                                      \\',
        '    bool exp_##NAME = false;                                                          \\',
        '    if (once_##NAME.compare_exchange_strong(exp_##NAME, true)) {                       \\',
        '        std::fprintf(stderr,                                                          \\',
        '            "[abnstub] " #NAME " called - reco_normal hook not ported "               \\',
        '            "(reco_abnormal twin = " #TWIN ", +8 split rule) [distinct fired: %d]\\n", \\',
        '            g_abn_stub_fired.fetch_add(1) + 1);                                       \\',
        '        std::fflush(stderr);                                                          \\',
        '    }', '', 'extern "C" {', '']
for s in unres:
    a = int(s[4:], 16)
    twin = s if a < SPLIT_LO else 'sub_%08X' % (a + 8)
    forms = ','.join(sorted(src.get(s, ['DIRECT-CALL'])))
    body.append('// %s: host ref form %s%s' % (s, forms,
                '   *** DIRECT CALL - a no-op here IS a behaviour change ***' if s in DIRECT else ''))
    body.append('PPC_WEAK_FUNC(__imp__%s) { (void)ctx; (void)base; ABN_STUB(%s, %s); }' % (s, s, twin))
body += ['', '} // extern "C"']

out = (H % (len(unres), len(DIRECT), ', '.join(DIRECT) or 'none')) + '\n' + '\n'.join(body) + '\n'
open(os.path.join(ABN, 'abn_hook_stubs.cpp'), 'w', encoding='utf-8', newline='\n').write(out)
print('wrote out_reco_abn/abn_hook_stubs.cpp: %d stubs (EXPECTED 0 - see header)' % len(unres))
print('unresolved:', ' '.join(unres))
cf = collections.Counter()
for s in unres:
    for x in src.get(s, ['DIRECT-CALL']):
        cf[x] += 1
print('ref forms:', dict(cf))
