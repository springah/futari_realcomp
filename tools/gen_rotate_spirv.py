"""Regenerate render/rotate_spirv.h (RT_ROTATE present pass SPIR-V) from shaders/rotate_{vs,ps}.hlsl.

Run from anywhere:  python -I tools/gen_rotate_spirv.py [path/to/dxc.exe]
Default dxc = ../_tools/XenosRecomp/thirdparty/dxc-bin/bin/x64/dxc.exe (sibling of this repo), or
$DXC. The SPIR-V is baked into the header so no shader compiler is needed at build time (the Mac
has none).
"""
import os, struct, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_DXC = os.path.join(os.path.dirname(ROOT), "_tools", "XenosRecomp", "thirdparty", "dxc-bin", "bin", "x64", "dxc.exe")
STAGES = [("kRotateVertSpv", "shaders/rotate_vs.hlsl", "vs_6_0"),
          ("kRotateFragSpv", "shaders/rotate_ps.hlsl", "ps_6_0")]


def compile_one(dxc, src, profile, out):
    cmd = [dxc, "-spirv", "-T", profile, "-E", "main", "-fspv-target-env=vulkan1.0", "-O3", src, "-Fo", out]
    subprocess.run(cmd, check=True)
    return cmd


def main():
    dxc = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("DXC", DEFAULT_DXC)
    lines = []
    with tempfile.TemporaryDirectory() as td:
        for name, rel, profile in STAGES:
            out = os.path.join(td, name + ".spv")
            compile_one(dxc, os.path.join(ROOT, rel), profile, out)
            data = open(out, "rb").read()
            assert len(data) % 4 == 0 and struct.unpack_from("<I", data)[0] == 0x07230203, rel
            words = struct.unpack("<%dI" % (len(data) // 4), data)
            lines.append("// %s  <-  dxc -spirv -T %s -E main -fspv-target-env=vulkan1.0 -O3 %s -Fo out.spv" % (name, profile, rel))
            lines.append("static const uint32_t %s[] = {" % name)
            for i in range(0, len(words), 6):
                lines.append("  " + ", ".join("0x%08x" % w for w in words[i:i + 6]) + ",")
            lines.append("};")
            lines.append("")
    hdr = [
        "// GENERATED by tools/gen_rotate_spirv.py -- do not edit. RT_ROTATE present pass (render/vk_render.cpp).",
        "// Sources: shaders/rotate_vs.hlsl, shaders/rotate_ps.hlsl; compiler: DXC 1.8.2407 (XenosRecomp dxc-bin).",
        "// Regenerate: python -I tools/gen_rotate_spirv.py   (each stage compiled with the command shown above it)",
        "#pragma once",
        "#include <cstdint>",
        "",
    ]
    path = os.path.join(ROOT, "render", "rotate_spirv.h")
    with open(path, "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(hdr + lines))
    print("wrote", path)


if __name__ == "__main__":
    main()
