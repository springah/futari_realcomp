#!/usr/bin/env python3
"""modtools.py - generic static bring-up tools for the non-reco game modules (w1107, 2026-11-07).

The kiniro bring-up (docs/PLAN_kiniro_bringup.md) wrote these as kiniro-specific scripts in out_kiniro/tools_kiniro/.
This file REUSES their machinery unchanged (gen_symbol_map.Tree / match / demand_side, derive_desc.xex_info / refs /
translate) and only parameterises the module, tree and output names, so hirow_* and palm_* follow the same method:

  symmap  --mod M --tree T --tag K [--check]   |   symmap --control
          reco_normal -> M whole-body matcher (UNIQUE / TIEBROKEN / AMBIGUOUS / NOMATCH); writes T/K_symbol_map.h,
          T/K_hook_stubs.cpp, T/tools_mod/hook_match_K.txt.  Dropped hooks -> sub_X_KDROP (same convention as kiniro).
          --control: reco_normal -> reco_abnormal must give 0 disagreements with the +8 law.
  desc    --mod M --tree T
          descriptor candidates: XEX entry/ordinal 1 (control: reco pair), .data addresses by twin vote for the six
          FutariModuleAddrs + nav set + START words + the RT_DIVGUARD divisor (control: reco_abnormal reproduces +0x60),
          and the RT_DIVGUARD twin (reco ShipCtor sub_8814DDC8's insn-159 registration -> the hook fn; its
          lis/lwz -> divwu divisor), plus a per-64K-block dominant .data delta table.
  split   --a M1 --ta T1 --b M2 --tb T2
          the code twin law between two sibling modules from their function starts (finds the insertion window).
  twin    --a M1 --ta T1 --b M2 --tb T2 --amap K1_symbol_map.h --tag K2 --lo 0x.. --hi 0x..
          composes M1's symbol map with the measured +8 law onto M2 (gen_symbol_map_abn.py's job, generic), then
          CROSS-CHECKS it against an independent reco_normal -> M2 matcher run (must agree on every common symbol).
  dtwin   --a M1 --ta T1 --b M2 --tb T2 --lo 0x.. --hi 0x.. --addrs name=0x..,name=0x..
          .data translation M1 -> M2 by +8-paired twin vote (derive_desc_abn.py, generic).
IMGDIR (env) = the flat images (scripts/regen_mod_mac.sh writes _local/modregen/img).
"""
import os, sys, re, collections
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
KT = os.path.join(REPO, 'out_kiniro', 'tools_kiniro')
sys.path.insert(0, KT)
import gen_symbol_map as G      # Tree, match, demand_side, norm (kiniro's, unchanged)
import derive_desc as D         # xex_info, refs, translate, TARGETS

IMGDIR = os.environ.get('IMGDIR', os.path.join(REPO, '_local', 'modregen', 'img'))
arg = G.arg


def tree(mod, tdir):
    return G.Tree(os.path.join(IMGDIR, mod + '.img.bin'), os.path.join(REPO, tdir, 'ppc_func_mapping.cpp'),
                  os.path.join(REPO, tdir, 'ppc_config.h'))


def uniq_map(src, dst):
    idx = collections.defaultdict(list)
    for s in dst.starts: idx[(dst.ext[s], dst.body(s))].append(s)
    u = {}
    for s in src.starts:
        c = idx.get((src.ext[s], src.body(s)))
        if c and len(c) == 1: u[s] = c[0]
    rev = collections.Counter(u.values())
    return {s: t for s, t in u.items() if rev[t] == 1}


def emit_map(mod, tdir, tag, res, refs, cnt, outdir=None, check=False, extra_hdr=()):
    shared = open(os.path.join(REPO, tdir, 'ppc_recomp_shared.h'), encoding='utf-8').read()
    syms = set(int(h, 16) for h in re.findall(r'PPC_EXTERN_FUNC\(sub_([0-9A-Fa-f]{8})\)', shared))
    renamed, same, dropped = {}, [], []
    for a, (cls, t, c, note) in sorted(res.items()):
        if t is None: dropped.append(a); continue
        if t not in syms: G.die('target 0x%08X of 0x%08X is not a %s function symbol' % (t, a, mod))
        if t == a: same.append(a)
        else: renamed[a] = t
    dup = [t for t, n in collections.Counter(renamed.values()).items() if n > 1] + [a for a in same if a in renamed.values()]
    if dup: G.die('two reco symbols onto one %s symbol: %s' % (mod, ', '.join('0x%08X' % t for t in dup)))
    keys = set(renamed) | set(dropped)
    # CHAIN BREAK (new for hirow/palm, whose code is displaced by small deltas such as +0x10): when a reco symbol A
    # maps onto module address B and B is ITSELF a renamed/dropped reco key, `#define sub_A sub_B` would rescan into
    # sub_B's own #define.  Such targets are spelled through an alias token sub_B_HCH whose declaration carries an
    # asm label naming the real symbol (Mach-O: __Z12sub_BR10PPCContextPh / ___imp__sub_B, measured with nm on the
    # kiniro objects), so the preprocessor never sees the target's name.
    chain = sorted(a for a, t in renamed.items() if t in keys)
    alias = {renamed[a] for a in chain}
    by = collections.defaultdict(list)
    for a, v in sorted(res.items()): by[v[0]].append(a)
    H = []; w = H.append
    w('// %s_symbol_map.h - GENERATED by tools/modbringup/modtools.py.  DO NOT EDIT.' % tag)
    w('//')
    w("// Force-included (clang -include) by build_mac_dll.sh's %s arm ONLY, onto the two TUs that ride into the" % tag)
    w('// %s module dylib and name reco_normal guest function symbols (out_reco/merged/merged_game.cpp and' % mod)
    w('// futari_decomp decomp/game/nvk_game_hooks.cpp).  Truth = a mnemonic whole-body match reco_normal -> %s' % mod)
    w("// (out_kiniro/tools_kiniro/gen_symbol_map.py's matcher, unchanged).  Positive control: reco_normal ->")
    w('// reco_abnormal, 0 disagreements with the +8 law.')
    for l in extra_hdr: w('// ' + l)
    w('//')
    w('// %d referenced symbols: %d UNIQUE, %d TIEBROKEN, %d AMBIGUOUS, %d NOMATCH.'
      % (len(res), cnt['UNIQUE'], cnt['TIEBROKEN'], cnt['AMBIGUOUS'], cnt['NOMATCH']))
    w('// %d renamed (address differs), %d at the same address (no #define), %d DROPPED -> sub_X_KDROP.'
      % (len(renamed), len(same), len(dropped)))
    w('// DROPPED = the override is renamed onto a name nothing in the %s tree references (never installed);' % mod)
    w('// any call into it reaches %s/%s_hook_stubs.cpp, which is LOUD ([kdrop], exit 97).' % (tdir, tag))
    w('#pragma once')
    w('#include <cstdint>')
    w('struct PPCContext;')
    w('')
    if alias:
        w('// ---- CHAIN-BREAK ALIASES (%d): targets that are themselves renamed reco keys (see modtools.py emit_map) ----' % len(alias))
        for t in sorted(alias):
            w('void sub_%08X_HCH(PPCContext& __restrict ctx, uint8_t* base) __asm__("__Z12sub_%08XR10PPCContextPh");' % (t, t))
            w('extern "C" void __imp__sub_%08X_HCH(PPCContext& __restrict ctx, uint8_t* base) __asm__("___imp__sub_%08X");' % (t, t))
        w('')
    for cls in ('UNIQUE', 'TIEBROKEN', 'AMBIGUOUS', 'NOMATCH'):
        w('// ---- %s (%d) ----' % (cls, len(by[cls])))
        for a in by[cls]:
            _, t, c, note = res[a]
            sn = 'sub_%08X' % a
            files = '/'.join(sorted(f.replace('.cpp', '') for f in refs[a]))
            if t is not None and t == a:
                w('//   %s  same address  [%s]%s' % (sn, files, ('  ' + note) if note else ''))
            elif t is not None:
                dn = 'sub_%08X' % t + ('_HCH' if t in alias else '')
                w('#define %-20s %-20s // %+#x [%s]%s' % (sn, dn, t - a, files, ('  ' + note) if note else ''))
                w('#define __imp__%-13s __imp__%s' % (sn, dn))
            else:
                dn = sn + '_KDROP'
                w('#define %-20s %-26s // [%s] %d cand. %s' % (sn, dn, files, len(c), note))
                w('#define __imp__%-13s __imp__%s' % (sn, dn))
                w('void %s(PPCContext& __restrict ctx, uint8_t* base);' % dn)
                w('extern "C" void __imp__%s(PPCContext& __restrict ctx, uint8_t* base);' % dn)
        w('')
    hdr = '\n'.join(H) + '\n'
    S = []; w = S.append
    w('// %s_hook_stubs.cpp - GENERATED by tools/modbringup/modtools.py.  DO NOT EDIT.' % tag)
    w('// One WEAK definition per DROPPED reco_normal hook symbol (%s_symbol_map.h); same contract as' % tag)
    w('// out_kiniro/kiniro_hook_stubs.cpp: a live hook calling a dropped one is reported and exits 97 unless RT_KDROP_CONT=1.')
    w('#include "ppc_recomp_shared.h"')
    w('#include <cstdio>')
    w('#include <cstdlib>')
    w('static void kdrop(const char* n) {')
    w('    static const bool cont = std::getenv("RT_KDROP_CONT") != nullptr;')
    w('    std::fprintf(stderr, "[kdrop] %%s: reco_normal hook symbol with no %s twin was CALLED%%s\\n",' % mod)
    w('                 n, cont ? " (RT_KDROP_CONT=1: no-op)" : " -> exit 97 (RT_KDROP_CONT=1 continues)");')
    w('    std::fflush(stderr);')
    w('    if (!cont) std::_Exit(97);')
    w('}')
    for a in dropped:
        dn = 'sub_%08X_KDROP' % a
        w('extern "C" __attribute__((weak)) PPC_FUNC(__imp__%s) { (void)ctx; (void)base; kdrop("__imp__%s"); }' % (dn, dn))
        w('__attribute__((weak)) PPC_FUNC(%s) { __imp__%s(ctx, base); }' % (dn, dn))
    stubs = '\n'.join(S) + '\n'
    R = ['# hook_match_%s.txt - GENERATED by tools/modbringup/modtools.py (evidence for %s_symbol_map.h)' % (tag, tag),
         '# addr class target delta candidates note files']
    for a, (cls, t, c, note) in sorted(res.items()):
        R.append('0x%08X %-9s %s %s %d %s [%s]' % (a, cls, ('0x%08X' % t) if t else '-', ('%+#x' % (t - a)) if t else '-',
                                                 len(c), note or '-', '/'.join(sorted(refs[a]))))
    report = '\n'.join(R) + '\n'
    od = outdir or os.path.join(REPO, tdir)
    os.makedirs(os.path.join(REPO, tdir, 'tools_mod'), exist_ok=True)
    outs = {os.path.join(od, tag + '_symbol_map.h'): hdr, os.path.join(od, tag + '_hook_stubs.cpp'): stubs,
            os.path.join(REPO, tdir, 'tools_mod', 'hook_match_%s.txt' % tag): report}
    if check:
        stale = [p for p, t in outs.items() if not os.path.exists(p) or open(p, encoding='utf-8').read() != t]
        print('CHECK: %s' % ('MATCH' if not stale else 'STALE ' + ' '.join(stale))); sys.exit(1 if stale else 0)
    for p, t in outs.items():
        with open(p, 'w', encoding='utf-8', newline='\n') as fh: fh.write(t)
        print('wrote %s' % os.path.relpath(p, REPO))
    print('renamed %d, same %d, dropped (%d): %s' % (len(renamed), len(same), len(dropped), ' '.join('0x%08X' % a for a in dropped)))
    return renamed, same, dropped


def cmd_symmap():
    src = tree('reco_normal', 'out_reco')
    if '--control' in sys.argv:
        dst = tree('reco_abnormal', 'out_reco_abn')
        res, _ = G.match(src, dst, G.demand_side(src))
        bad = [a for a, v in res.items() if v[1] is not None and ((a < 0x880DEF88 and v[1] != a) or (a >= 0x880DF080 and v[1] != a + 8))]
        print('CONTROL reco_normal->reco_abnormal: %d matched, %d disagreements with the +8 law'
              % (sum(1 for v in res.values() if v[1] is not None), len(bad)))
        sys.exit(1 if bad else 0)
    mod, tdir, tag = arg('--mod'), arg('--tree'), arg('--tag')
    dst = tree(mod, tdir)
    refs = G.demand_side(src)
    res, uniq = G.match(src, dst, refs)
    cnt = collections.Counter(v[0] for v in res.values())
    print('%s: %d referenced reco_normal function symbols -> %s; global unique body matches %d/%d'
          % (mod, len(res), dict(cnt), len(uniq), len(src.starts)))
    emit_map(mod, tdir, tag, res, refs, cnt, outdir=arg('--outdir'), check='--check' in sys.argv)


def divguard(src, dst, uniq):
    """RT_DIVGUARD twin (PLAN_kiniro_bringup step 3f routes 1 + 4)."""
    ctor = uniq.get(0x8814DDC8)
    if ctor is None: return 'ShipCtor 0x8814DDC8 has no UNIQUE twin -> hunt by hand'
    rd = dict(D.refs(dst, ctor)); cb = rd.get(159)
    rs = dict(D.refs(src, 0x8814DDC8))
    out = 'ShipCtor 0x8814DDC8 -> 0x%08X; reco insn159 ref 0x%08X; twin insn159 ref %s' % (ctor, rs.get(159, 0), ('0x%08X' % cb) if cb else 'NONE')
    if not cb or cb not in dst.set: return out + ' (not a function start -> hunt by hand)'
    reg = {}
    for k in range(dst.ext[cb] // 4):
        x = dst.w(cb + 4 * k); op = x >> 26; rt = (x >> 21) & 31; ra = (x >> 16) & 31; rb = (x >> 11) & 31
        si = x & 0xFFFF; si = si - 0x10000 if si & 0x8000 else si
        if op == 15 and ra == 0: reg[rt] = ('hi', (si << 16) & 0xFFFFFFFF); continue
        if op == 32 and ra in reg and reg[ra][0] == 'hi': reg[rt] = ('ld', (reg[ra][1] + si) & 0xFFFFFFFF, k); continue
        if op == 31 and ((x >> 1) & 0x3FF) == 459:   # divwu
            if rb in reg and reg[rb][0] == 'ld':
                return out + '; divwu at insn %d divisor .data 0x%08X (lwz insn %d); fn %d insns' % (k, reg[rb][1], reg[rb][2], dst.ext[cb] // 4)
    return out + '; no lis/lwz->divwu found'


def cmd_desc():
    mod, tdir = arg('--mod'), arg('--tree')
    xexdir = os.path.join(REPO, 'assets', 'media', 'Module')
    trees = {'reco_normal': tree('reco_normal', 'out_reco'), 'reco_abnormal': tree('reco_abnormal', 'out_reco_abn'), mod: tree(mod, tdir)}
    print('== 1. XEX headers (control: reco_normal 0x88070588/0x8824E698, reco_abnormal ord1 0x8824E6A0)')
    for m, t in trees.items():
        e, x, o = D.xex_info(os.path.join(xexdir, m + '.xex'), t)
        print('  %-14s entry=0x%08X  export_table=0x%08X  ordinal1=%s' % (m, e or 0, x, ('0x%08X' % o) if o else 'NOT IN IMAGE'))
    src = trees['reco_normal']
    D.TARGETS = D.TARGETS + [('divisor', 0x887ACE14)]
    for m in ('reco_abnormal', mod):
        dst = trees[m]; uniq = uniq_map(src, dst)
        votes = D.translate(src, dst, uniq)
        print('== 2. .data by twin: reco_normal -> %s (%d unique twins)%s' % (m, len(uniq), '  [control: +0x60 at/above 0x88351830]' if m == 'reco_abnormal' else ''))
        for name, a in D.TARGETS:
            v = votes[a].most_common(4); tot = sum(votes[a].values())
            best = ('0x%08X (%+#x) %d/%d' % (v[0][0], v[0][0] - a, v[0][1], tot)) if v else 'NO REFERENCING TWIN'
            rest = '  others: ' + ', '.join('0x%08X x%d' % kv for kv in v[1:]) if len(v) > 1 else ''
            print('  %-15s 0x%08X -> %s%s' % (name, a, best, rest))
        print('== 3. RT_DIVGUARD twin (%s): %s' % (m, divguard(src, dst, uniq)))
        hist = collections.Counter()
        for s, t in uniq.items():
            rd = dict(D.refs(dst, t))
            for k, ea in D.refs(src, s):
                if 0x88250000 <= ea < 0x887B0000 and k in rd: hist[(ea >> 12, rd[k] - ea)] += 1
        top = collections.defaultdict(list)
        for (blk, d), n in hist.items(): top[blk].append((n, d))
        print('== 4. per-4K .data page dominant delta near the targets (page: delta x votes/total)')
        pages = sorted(set(a >> 12 for _, a in D.TARGETS))
        print('  ' + '  '.join('%05X:%+#x x%d/%d' % (b, max(top[b])[1], max(top[b])[0], sum(n for n, _ in top[b])) if top.get(b) else '%05X:-' % b for b in pages))


def law(s, lo, hi):
    return s if s <= lo else (s + 8 if s >= hi else None)


def cmd_split():
    a, b = tree(arg('--a'), arg('--ta')), tree(arg('--b'), arg('--tb'))
    sb = b.set
    mv = [s for s in a.starts if s + 8 in sb and s not in sb]
    keep = [s for s in a.starts if s in sb]
    hi = min(mv) if mv else None
    lo = max(s for s in keep if hi is None or s < hi)
    ok = sum(1 for s in a.starts if law(s, lo, hi or 1 << 40) in sb)
    print('%s -> %s: keep <= 0x%08X, +8 >= %s; %d/%d function starts obey the law' % (
        arg('--a'), arg('--b'), lo, ('0x%08X' % hi) if hi else '-', ok, len(a.starts)))
    print('  insertion function 0x%08X: extent %#x -> %#x' % (lo, a.ext[lo], b.ext.get(lo, 0)))


def cmd_twin():
    an, at, bn, bt, amap, tag = arg('--a'), arg('--ta'), arg('--b'), arg('--tb'), arg('--amap'), arg('--tag')
    a, b = tree(an, at), tree(bn, bt)
    lo, hi = int(arg('--lo'), 16), int(arg('--hi'), 16)
    starts_ok = sum(1 for s in a.starts if law(s, lo, hi) in b.set)
    print('+8 law control: %d/%d %s starts land on a %s start' % (starts_ok, len(a.starts), an, bn))
    txt = open(os.path.join(REPO, at, amap)).read()
    src = tree('reco_normal', 'out_reco'); refs = G.demand_side(src)
    res = {}
    for m in re.finditer(r'^#define (sub_[0-9A-F]{8}) +(sub_[0-9A-F]{8})(_KDROP|_HCH)? +// (.*)$', txt, re.M):
        ra = int(m.group(1)[4:], 16)
        if m.group(3) == '_KDROP': res[ra] = ('NOMATCH' if ' 0 cand.' in m.group(4) else 'AMBIGUOUS', None, [], 'dropped in ' + amap)
        else:
            t = law(int(m.group(2)[4:], 16), lo, hi)
            if t is None: G.die('twin of 0x%08X falls in the insertion window' % ra)
            res[ra] = ('UNIQUE', t, [t], 'composed +8 law from ' + amap)
    for m in re.finditer(r'^//   (sub_[0-9A-F]{8})  same address', txt, re.M):
        ra = int(m.group(1)[4:], 16); t = law(ra, lo, hi)
        if t is None: G.die('same-address 0x%08X falls in the insertion window' % ra)
        res[ra] = ('UNIQUE', t, [t], 'composed +8 law from ' + amap)
    ind, _ = G.match(src, b, refs)
    common = [x for x in res if x in ind and res[x][1] is not None and ind[x][1] is not None]
    dis = [(x, res[x][1], ind[x][1]) for x in common if res[x][1] != ind[x][1]]
    print('cross-check vs independent reco_normal->%s matcher: %d common mapped, %d DISAGREE %s' % (
        bn, len(common), len(dis), ' '.join('0x%08X:%08X/%08X' % d for d in dis[:8])))
    if dis: sys.exit(1)
    cnt = collections.Counter(v[0] for v in res.values())
    emit_map(bn, bt, tag, res, {k: refs.get(k, {'?'}) for k in res}, cnt, check='--check' in sys.argv,
             extra_hdr=('COMPOSED from %s/%s by the +8 twin law (keep <= 0x%08X, +8 >= 0x%08X); cross-checked against an' % (at, amap, lo, hi),
                        'independent reco_normal -> %s matcher run: %d common mapped symbols, 0 disagreements.' % (bn, len(common))))


def cmd_dtwin():
    an, at, bn, bt = arg('--a'), arg('--ta'), arg('--b'), arg('--tb')
    lo, hi = int(arg('--lo'), 16), int(arg('--hi'), 16)
    a, b = tree(an, at), tree(bn, bt)
    uniq = {s: law(s, lo, hi) for s in a.starts if law(s, lo, hi) in b.set}
    tg = [(kv.split('=')[0], int(kv.split('=')[1], 16)) for kv in arg('--addrs').split(',')]
    D.TARGETS = tg
    votes = D.translate(a, b, uniq)
    for name, x in tg:
        v = votes[x].most_common(4); tot = sum(votes[x].values())
        print('  %-15s 0x%08X -> %s' % (name, x, ('0x%08X (%+#x) %d/%d%s' % (v[0][0], v[0][0] - x, v[0][1], tot,
              ('  others: ' + ', '.join('0x%08X x%d' % kv for kv in v[1:])) if len(v) > 1 else '')) if v else 'NO REFERENCING TWIN'))


if __name__ == '__main__':
    {'symmap': cmd_symmap, 'desc': cmd_desc, 'split': cmd_split, 'twin': cmd_twin, 'dtwin': cmd_dtwin}[sys.argv[1]]()
