#!/bin/bash
# gen_xrgen.sh — reproducible RVK_XRGEN pipeline: ROM shader containers -> XenosRecomp
# (branch glvl-d3d9) HLSL -> thin plumbing shim GLSL -> SPIR-V -> render/xrgen_shaders.h.
#
# Replaces our HAND-SYNTHESIZED ROM shader translations with GENERATED ones. The µcode->HLSL
# step is done by XenosRecomp (provably follows the µcode); hlsl2glsl_xrgen.py adapts ONLY the
# interface (register consts -> RawBufferLoad, sampler2D/tex2D -> bindless, semantics -> loc,
# + the fixed-function alpha test / the vs px->ndc epilogue). No shader math is authored here.
#
# Inputs (in tools/xrgen/, all harvested from the guest-memory captures):
#   rom_ps50.xpu — entry 50, byte-exact from caps_gp/cap_gimage.bin @0x94D0
#   rom_ps49.xpu — entry 49, byte-exact from caps_gp/cap_image.bin  @0x3DBD8 (guest 0x8203DBD8;
#                  code-after-DEF-pool == runtime ucode 0x86D2040 family, verified byte-identical)
#   rom_vs48.xvu — entry 48, SYNTHESIZED METADATA around the genuine dumped runtime ucode
#                  (no container exists in any capture — see make_vs48_container.py)
#   rom_vs45.xvu — entry 45, byte-exact from caps_gp/cap_gimage.bin @0x9638 (guest 0x88009638)
#   rom_vs47.xvu — entry 47, byte-exact from caps_gp/cap_gimage.bin @0x98A8 (guest 0x880098A8)
#                  (both real containers, carved by make_vs4547_containers.py — FIX-A 2026-07-29:
#                  the BAKED modules for 45/47 predate the px->ndc epilogue and do not even
#                  DECLARE the pc.ndc push members, so their VTE-off draws emitted clip = px)
#   shell_ps22/26/28/40.xpu — shader-table rows 22/26/28/40, byte-exact from cap_image.bin
#                  @0x3E2C8 / @0x3EE88 / @0x3F588 / @0x43A38, carved by
#                  make_shellps_containers.py (CHROMA FIX 2 — s2B leg 14, 2026-07-30).
#                  The SETP_INV census found these four are the rest of the shell's HSV
#                  colour-filter family: same predicate-stack ladder as row 20 / entry 49
#                  (5x SETP_INV, 6x PRED_SET*_PUSH, 5x SETP_POP), and their BAKED modules each
#                  carry 5 unguarded SETP_INV sites. See _tmpscripts/setpinv_audit_report.md.
#
#   XR_SRC : path to XenosRecomp/XenosRecomp (glvl-d3d9 branch @ be84413). Default = the
#            VENDORED clone (campaign C0, 2026-07-28: the /c/tmp clone was lost to a tmp
#            cleanup — re-cloned from hedge-dev upstream and pinned in tools/).
#   CXX    : clang++ (msvc target). default matches build_win.sh
set -e
cd "$(dirname "$0")"
XR_SRC="${XR_SRC:-/c/Users/shant/Desktop/projects/futari_realcomp/tools/XenosRecomp/XenosRecomp}"
CXX="${CXX:-/c/Program Files/LLVM/bin/clang++.exe}"
GLSLC="${GLSLC:-/c/VulkanSDK/1.4.350.0/Bin/glslc.exe}"
T=tools/xrgen
mkdir -p "$T"

echo "== [1/6] build xrgen harness (clang++, std::format fmt shim, no FXC) =="
"$CXX" --target=x86_64-pc-windows-msvc -std=c++20 -O1 -D_CRT_SECURE_NO_WARNINGS -Wno-macro-redefined -Wno-switch \
  -include "$T/my_pch.h" -I "$XR_SRC" \
  "$T/xrgen_main.cpp" "$XR_SRC/shader_recompiler.cpp" -o "$T/xrgen.exe"

echo "== [2/6] synthesize the vs48 container (metadata around the real ucode) =="
python "$T/make_vs48_container.py"
echo "== [2b/6] carve the vs45/vs47 containers (byte-exact, no synthesis) =="
python "$T/make_vs4547_containers.py"
echo "== [2c/6] carve the shell PS 22/26/28/40 containers (byte-exact, no synthesis) =="
python "$T/make_shellps_containers.py"

# shader table: name -> guest_addr [+ --athresh for ps entries: the appended fixed-function
# alpha test is a no-op unless armed (athresh=0 when RB_COLORCONTROL disables it)]
# NOTE: ATEST is PIXEL-SHADER-ONLY; the vs entries never carry it.
NAMES="rom_vs45 rom_vs47 rom_vs48 rom_ps49 rom_ps50 shell_ps22 shell_ps26 shell_ps28 shell_ps40"
declare -A GUEST=( [rom_vs45]=0x88009638ULL [rom_vs47]=0x880098a8ULL
                   [rom_vs48]=0xf4c1040ULL [rom_ps49]=0x86d2040ULL [rom_ps50]=0x11720000ULL
                   [shell_ps22]=0x8203e2c8ULL [shell_ps26]=0x8203ee88ULL
                   [shell_ps28]=0x8203f588ULL [shell_ps40]=0x82043a38ULL )
declare -A ATEST=( [rom_ps49]=--athresh [rom_ps50]=--athresh
                   [shell_ps22]=--athresh [shell_ps26]=--athresh
                   [shell_ps28]=--athresh [shell_ps40]=--athresh )
declare -A STAGE=( [rom_vs45]=vert [rom_vs47]=vert [rom_vs48]=vert [rom_ps49]=frag [rom_ps50]=frag
                   [shell_ps22]=frag [shell_ps26]=frag [shell_ps28]=frag [shell_ps40]=frag )
declare -A EXT=(   [rom_vs45]=xvu  [rom_vs47]=xvu  [rom_vs48]=xvu  [rom_ps49]=xpu  [rom_ps50]=xpu
                   [shell_ps22]=xpu [shell_ps26]=xpu [shell_ps28]=xpu [shell_ps40]=xpu )

HDR=xrgen_shaders.h
{
  echo "// Auto-generated by render/gen_xrgen.sh — DO NOT EDIT BY HAND."
  echo "// GENERATED replacements (XenosRecomp glvl-d3d9) for the hand-synth ROM shaders,"
  echo "// selected at runtime by RVK_XRGEN. See gen_xrgen.sh / tools/hlsl2glsl_xrgen.py."
  echo "#pragma once"
  echo
} > "$HDR"

for name in $NAMES; do
  echo "== [3/6] $name: XenosRecomp container -> HLSL =="
  "$T/xrgen.exe" "$T/$name.${EXT[$name]}" "$T/$name.hlsl" "$T/shader_common.h"
  echo "== [4/6] $name: HLSL -> GLSL (plumbing shim ${ATEST[$name]:-}) =="
  python tools/hlsl2glsl_xrgen.py "$T/$name.hlsl" "$T/$name.glsl" ${ATEST[$name]:-}
  echo "== [5/6] $name: GLSL -> SPIR-V =="
  "$GLSLC" -O -fshader-stage=${STAGE[$name]} --target-env=vulkan1.2 "$T/$name.glsl" -o "$T/$name.spv"
  python - "$name" "$T/$name.spv" "${GUEST[$name]}" >> "$HDR" <<'PY'
import sys,struct
name,spv,guest=sys.argv[1],sys.argv[2],sys.argv[3]
w=struct.unpack(f'<{len(open(spv,"rb").read())//4}I',open(spv,'rb').read())
arr=',\n\t'.join(','.join(f'0x{x:08X}u' for x in w[i:i+8]) for i in range(0,len(w),8))
print(f'static const unsigned g_xrgen_spirv_{name}[{len(w)}] = {{\n\t{arr},\n}};\n')
print(f'// guest_addr {guest} -> this generated module')
PY
done

# emit the lookup table
{
  echo
  echo "typedef struct { unsigned long long guest_addr; const unsigned* spirv; unsigned spirv_dwords; } XrgenShader;"
  echo "static const XrgenShader g_xrgen_shaders[] = {"
  for name in $NAMES; do
    n=$(python - "$T/$name.spv" <<'PY'
import sys;print(len(open(sys.argv[1],'rb').read())//4)
PY
)
    echo "  { ${GUEST[$name]}, g_xrgen_spirv_$name, ${n}u },"
  done
  echo "};"
  echo "static const unsigned g_xrgen_shader_count = sizeof(g_xrgen_shaders)/sizeof(g_xrgen_shaders[0]);"
} >> "$HDR"

echo "== [6/6] wrote render/$HDR =="
grep -c "g_xrgen_spirv" "$HDR"
