#!/bin/bash
# Compile the sprite shaders to SPIR-V and embed as a C header (self-contained runtime,
# no shaderc dependency). Re-run when the .vert/.frag change.
set -e
cd "$(dirname "$0")"
glslc sprite.vert -o /tmp/sprite.vert.spv
glslc sprite.frag -o /tmp/sprite.frag.spv
{
  echo "// Generated by gen_shaders.sh — do not edit. SPIR-V for sprite.vert / sprite.frag."
  echo "#pragma once"
  echo "#include <cstdint>"
  echo -n "static const uint32_t kSpriteVertSpv[] = {"
  od -An -tx4 -v /tmp/sprite.vert.spv | tr -s ' ' '\n' | grep . | sed 's/^/0x/;s/$/,/' | tr '\n' ' '
  echo "};"
  echo -n "static const uint32_t kSpriteFragSpv[] = {"
  od -An -tx4 -v /tmp/sprite.frag.spv | tr -s ' ' '\n' | grep . | sed 's/^/0x/;s/$/,/' | tr '\n' ' '
  echo "};"
} > shaders_spv.h
echo "wrote render/shaders_spv.h (vert $(stat -c%s /tmp/sprite.vert.spv)B, frag $(stat -c%s /tmp/sprite.frag.spv)B)"
