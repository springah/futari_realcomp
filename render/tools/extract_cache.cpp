// extract_cache.cpp
//
// Build-time tool: decodes the XenosRecomp shader cache (shader_cache_shell.h)
// and cross-references it against the raw ShaderContainer blobs found in the
// captured guest memory images (cap_image.bin / cap_gimage.bin), producing a
// self-contained, embeddable header (shaders_futari.h) for the Vulkan
// renderer: guest address + shader stage + microcode prefix key + SPIR-V.
//
// Pipeline:
//   1. Pull in the generated shader_cache_shell.h (entries + compressed
//      SMOL-V/ZSTD SPIR-V blob) via our minimal shader_cache.h.
//   2. ZSTD_decompress the whole SPIR-V cache once, then smolv::Decode each
//      entry's slice back into real SPIR-V, validating the 0x07230203 magic.
//   3. Re-scan cap_image.bin (guest base 0x82000000) and cap_gimage.bin
//      (guest base 0x88000000) for ShaderContainer signatures, using the
//      exact scan/accept logic from XenosRecomp/main.cpp:86-110.
//   4. Hash each found container with XXH3_64bits and match it against the
//      cache entries by hash.
//   5. Emit shaders_futari.h + per-shader .spv dumps.
//
// This file is a build-time host tool only; it is never linked into the
// game/runtime.

#include "shader_cache.h"
