// ---------------------------------------------------------------------
// Little utility: read an entire file into a byte vector.
// ---------------------------------------------------------------------
bool readFile(const std::string& path, std::vector<uint8_t>& out)
{
    std::ifstream f(path, std::ios::binary | std::ios::ate);
    if (!f)
        return false;

    std::streamsize size = f.tellg();
    if (size < 0)
        return false;

    f.seekg(0, std::ios::beg);
    out.resize(static_cast<size_t>(size));
    if (size > 0 && !f.read(reinterpret_cast<char*>(out.data()), size))
        return false;

    return true;
}

uint32_t bswap32(uint32_t v)
{
    return ((v & 0x000000FFu) << 24) |
           ((v & 0x0000FF00u) << 8) |
           ((v & 0x00FF0000u) >> 8) |
           ((v & 0xFF000000u) >> 24);
}

uint32_t readBE32(const uint8_t* p)
{
    uint32_t v;
    std::memcpy(&v, p, sizeof(v));
    return bswap32(v);
}

// ShaderContainer header layout (all big-endian uint32_t), from
// ~/UnleashedRecomp/tools/XenosRecomp/XenosRecomp/shader.h:
//   0: flags
//   4: virtualSize
//   8: physicalSize
//  12: fieldC
//  16: constantTableOffset
//  20: definitionTableOffset
//  24: shaderOffset
//  28: field1C
//  32: field20
// sizeof(ShaderContainer) == 36 bytes (9 x be<uint32_t>, no padding).
constexpr size_t kShaderContainerSize = 36;

struct FoundContainer
{
    size_t fileOffset;
    uint32_t flags;
    uint32_t virtualSize;
    uint32_t physicalSize;
    uint64_t hash;
    bool isPixel;
};

// Mirrors the exact scan/accept logic of XenosRecomp/main.cpp:86-110.
std::vector<FoundContainer> scanContainers(const std::vector<uint8_t>& data)
{
    std::vector<FoundContainer> found;
    const uint8_t* base = data.data();
    size_t fileSize = data.size();

    for (size_t i = 0; fileSize > kShaderContainerSize && i < fileSize - kShaderContainerSize - 1;)
    {
        const uint8_t* c = base + i;

        uint32_t flags = readBE32(c + 0);
        uint32_t virtualSize = readBE32(c + 4);
        uint32_t physicalSize = readBE32(c + 8);
        uint32_t field1C = readBE32(c + 28);
        uint32_t field20 = readBE32(c + 32);

        uint32_t dataSize32 = virtualSize + physicalSize; // uint32_t add, matches source
        size_t dataSize = dataSize32;

        if ((flags & 0xFFFFFF00u) == 0x102A1100u &&
            dataSize <= (fileSize - i) &&
            field1C == 0 &&
            field20 == 0)
        {
            uint64_t hash = XXH3_64bits(c, dataSize);

            FoundContainer fc;
            fc.fileOffset = i;
            fc.flags = flags;
            fc.virtualSize = virtualSize;
            fc.physicalSize = physicalSize;
            fc.hash = hash;
            fc.isPixel = (flags & 0x1u) == 0u; // shader_recompiler.cpp:1111
            found.push_back(fc);

            i += dataSize;
        }
        else
        {
            i += sizeof(uint32_t);
        }
    }

    return found;
}

std::string hexBytes(const uint8_t* p, size_t n)
{
    static const char* hex = "0123456789abcdef";
    std::string s;
    s.reserve(n * 2);
    for (size_t i = 0; i < n; i++)
    {
        s.push_back(hex[(p[i] >> 4) & 0xF]);
        s.push_back(hex[p[i] & 0xF]);
    }
    return s;
}

struct EmitDef { int reg; uint32_t v[4]; };
// Parse a ShaderContainer's definition table -> float4 constants (as u32 bit patterns).
// Mirrors XenosRecomp shader_recompiler.cpp:1374-1419. c = container base in file data.
// These are the shader-EMBEDDED constants (e.g. c255 the sprite screen transform) that the
// guest never sets via PM4 — so a faithful PM4 decoder can't recover them; bake them here.
static std::vector<EmitDef> parseDefs(const uint8_t* c, uint32_t virtualSize, bool isPixel)
{
    std::vector<EmitDef> defs;
    uint32_t defOff = readBE32(c + 20);
    if (!defOff) return defs;
    const uint8_t* dp = c + defOff + 20;   // DefinitionTable.definitions[] (skip 5-dword header)
    int guard = 0;
    while (readBE32(dp) != 0 && guard++ < 256)
    {
        uint32_t hdr = readBE32(dp), regIdx = hdr >> 16, count = hdr & 0xFFFFu, physOff = readBE32(dp + 4);
        for (uint32_t k = 0; k < (count + 3u) / 4u; k++)
        {
            int reg = (int)regIdx + (int)k - (isPixel ? 256 : 0);
            const uint8_t* va = c + virtualSize + physOff + k * 16;
            if (reg >= 0 && reg < (isPixel ? 224 : 256))
            {
                EmitDef e; e.reg = reg;
                for (int j = 0; j < 4; j++) e.v[j] = readBE32(va + j * 4);
                defs.push_back(e);
            }
        }
        dp += 8;
    }
    return defs;
}

