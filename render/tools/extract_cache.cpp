int main(int argc, char** argv)
{
    const char* shellPath = "/home/shant/xr-work/caps_s8/cap_image.bin";
    const char* gamePath = "/home/shant/xr-work/caps_s8/cap_gimage.bin";
    const char* outHeaderPath = "/home/shant/xr-work/render/shaders_futari.h";
    const char* outSpvDir = "/home/shant/xr-work/shaders/spv";
    const uint64_t kShellGuestBase = 0x82000000ull;
    const uint64_t kGameGuestBase = 0x88000000ull;

    if (argc > 1) shellPath = argv[1];
    if (argc > 2) gamePath = argv[2];

    int exitCode = 0;

    // -------------------------------------------------------------
    // Step 1+2: decompress + SMOL-V decode the shader cache.
    // -------------------------------------------------------------
    printf("== Shader cache ==\n");
    printf("entries: %zu\n", g_shaderCacheEntryCount);
    printf("spirv cache: compressed=%zu decompressed=%zu\n",
        g_spirvCacheCompressedSize, g_spirvCacheDecompressedSize);

    std::vector<uint8_t> spirvDecompressed(g_spirvCacheDecompressedSize);
    size_t dres = ZSTD_decompress(spirvDecompressed.data(), spirvDecompressed.size(),
        g_compressedSpirvCache, g_spirvCacheCompressedSize);
    if (ZSTD_isError(dres))
    {
        fprintf(stderr, "ZSTD_decompress failed: %s\n", ZSTD_getErrorName(dres));
        return 1;
    }
    if (dres != g_spirvCacheDecompressedSize)
    {
        fprintf(stderr, "ZSTD_decompress size mismatch: got %zu expected %zu\n",
            dres, g_spirvCacheDecompressedSize);
        return 1;
    }

    // Per cache-entry decoded SPIR-V (index-parallel with g_shaderCacheEntries).
    std::vector<std::vector<uint32_t>> entrySpirv(g_shaderCacheEntryCount);
    size_t decodeFailures = 0;

    for (size_t i = 0; i < g_shaderCacheEntryCount; i++)
    {
        const ShaderCacheEntry& e = g_shaderCacheEntries[i];
        const void* smolvData = spirvDecompressed.data() + e.spirvOffset;
        size_t smolvSize = e.spirvSize;

        size_t spirvSize = smolv::GetDecodedBufferSize(smolvData, smolvSize);
        if (spirvSize == 0 || (spirvSize % 4) != 0)
        {
            fprintf(stderr, "entry %zu (hash 0x%llX): GetDecodedBufferSize failed\n",
                i, (unsigned long long)e.hash);
            decodeFailures++;
            continue;
        }

        std::vector<uint32_t> spirv(spirvSize / 4);
        bool ok = smolv::Decode(smolvData, smolvSize, spirv.data(), spirvSize);
        if (!ok)
        {
            fprintf(stderr, "entry %zu (hash 0x%llX): smolv::Decode failed\n",
                i, (unsigned long long)e.hash);
            decodeFailures++;
            continue;
        }

        if (spirv.empty() || spirv[0] != 0x07230203u)
        {
            fprintf(stderr, "entry %zu (hash 0x%llX): bad SPIR-V magic 0x%08X\n",
                i, (unsigned long long)e.hash, spirv.empty() ? 0 : spirv[0]);
            decodeFailures++;
            continue;
        }

        entrySpirv[i] = std::move(spirv);
    }

    printf("decoded: %zu / %zu (failures: %zu)\n",
        g_shaderCacheEntryCount - decodeFailures, g_shaderCacheEntryCount, decodeFailures);
    if (decodeFailures != 0)
        exitCode = 1;

    // hash -> entry index
    std::unordered_map<uint64_t, size_t> hashToEntry;
    for (size_t i = 0; i < g_shaderCacheEntryCount; i++)
        hashToEntry.emplace(g_shaderCacheEntries[i].hash, i);

    // -------------------------------------------------------------
    // Step 3: scan the two guest memory images for containers.
    // -------------------------------------------------------------
    std::vector<uint8_t> shellData, gameData;
    if (!readFile(shellPath, shellData))
    {
        fprintf(stderr, "failed to read %s\n", shellPath);
        return 1;
    }
    if (!readFile(gamePath, gameData))
    {
        fprintf(stderr, "failed to read %s\n", gamePath);
        return 1;
    }

    std::vector<FoundContainer> shellContainers = scanContainers(shellData);
    std::vector<FoundContainer> gameContainers = scanContainers(gameData);

    printf("\n== Container scan ==\n");
    printf("shell (cap_image.bin):  %zu containers\n", shellContainers.size());
    printf("game  (cap_gimage.bin): %zu containers\n", gameContainers.size());

    // -------------------------------------------------------------
    // Step 4: match containers to cache entries by hash.
    // -------------------------------------------------------------
    struct MatchedShader
    {
        uint64_t guestAddr;
        bool isPixel;
        uint32_t ucodeSize;
        uint8_t ucodePrefix[32];
        size_t entryIndex;
        const uint8_t* containerBase; // for guest-relative uses (spv dump naming)
    };

    std::vector<MatchedShader> matched;
    std::vector<size_t> entryMatchCount(g_shaderCacheEntryCount, 0);
    size_t unmatchedContainers = 0;

    auto processImage = [&](std::vector<FoundContainer>& containers, const std::vector<uint8_t>& data, uint64_t guestBase)
    {
        for (const auto& c : containers)
        {
            auto it = hashToEntry.find(c.hash);
            if (it == hashToEntry.end())
            {
                fprintf(stderr, "WARNING: container @ file offset 0x%zX (hash 0x%llX) has no matching cache entry\n",
                    c.fileOffset, (unsigned long long)c.hash);
                unmatchedContainers++;
                continue;
            }

            size_t entryIdx = it->second;
            entryMatchCount[entryIdx]++;

            MatchedShader ms{};
            ms.guestAddr = guestBase + c.fileOffset;
            ms.isPixel = c.isPixel;
            ms.ucodeSize = c.physicalSize;
            ms.entryIndex = entryIdx;
            ms.containerBase = data.data() + c.fileOffset;

            const uint8_t* ucode = data.data() + c.fileOffset + c.virtualSize;
            size_t prefixLen = std::min<size_t>(32, c.physicalSize);
            std::memset(ms.ucodePrefix, 0, sizeof(ms.ucodePrefix));
            std::memcpy(ms.ucodePrefix, ucode, prefixLen);

            matched.push_back(ms);
        }
    };

    processImage(shellContainers, shellData, kShellGuestBase);
    processImage(gameContainers, gameData, kGameGuestBase);

    size_t totalContainers = shellContainers.size() + gameContainers.size();
    size_t claimedEntries = 0;
    for (size_t i = 0; i < g_shaderCacheEntryCount; i++)
        if (entryMatchCount[i] > 0)
            claimedEntries++;

    printf("\n== Hash matching ==\n");
    printf("total containers: %zu, matched: %zu, unmatched: %zu\n",
        totalContainers, matched.size(), unmatchedContainers);
    printf("cache entries claimed by >=1 container: %zu / %zu\n",
        claimedEntries, g_shaderCacheEntryCount);
    if (claimedEntries != g_shaderCacheEntryCount || unmatchedContainers != 0)
        exitCode = 1;

    // -------------------------------------------------------------
    // Verify the two known shaders.
    // -------------------------------------------------------------
    printf("\n== Known-shader verification ==\n");
    const uint64_t kKnownVS = 0x8203A330ull;
    const uint64_t kKnownPS = 0x8203A508ull;
    bool foundVS = false, foundPS = false;

    for (const auto& ms : matched)
    {
        if (ms.guestAddr == kKnownVS)
        {
            foundVS = true;
            printf("VS @ 0x%llX: is_pixel=%d ucode_size=%u prefix=%s\n",
                (unsigned long long)ms.guestAddr, ms.isPixel ? 1 : 0, ms.ucodeSize,
                hexBytes(ms.ucodePrefix, 32).c_str());
            if (ms.isPixel)
            {
                fprintf(stderr, "ERROR: known VS shader classified as pixel!\n");
                exitCode = 1;
            }

            // Cross-check against raw bytes at cap_image.bin file offset 0x3A448
            // (0x8203A330 - 0x82000000 + virtualSize 0x118 = 0x3A448).
            size_t rawOffset = 0x3A448;
            bool eq = (rawOffset + 32 <= shellData.size()) &&
                std::memcmp(shellData.data() + rawOffset, ms.ucodePrefix, 32) == 0;
            printf("  cross-check vs cap_image.bin@0x%zX: %s\n", rawOffset, eq ? "MATCH" : "MISMATCH");
            if (!eq)
                exitCode = 1;
        }
        if (ms.guestAddr == kKnownPS)
        {
            foundPS = true;
            printf("PS @ 0x%llX: is_pixel=%d ucode_size=%u prefix=%s\n",
                (unsigned long long)ms.guestAddr, ms.isPixel ? 1 : 0, ms.ucodeSize,
                hexBytes(ms.ucodePrefix, 32).c_str());
            if (!ms.isPixel)
            {
                fprintf(stderr, "ERROR: known PS shader classified as vertex!\n");
                exitCode = 1;
            }
        }
    }

    if (!foundVS) { fprintf(stderr, "ERROR: known VS @ 0x%llX not found among matched containers\n", (unsigned long long)kKnownVS); exitCode = 1; }
    if (!foundPS) { fprintf(stderr, "ERROR: known PS @ 0x%llX not found among matched containers\n", (unsigned long long)kKnownPS); exitCode = 1; }

    // -------------------------------------------------------------
    // Step 5: emit shaders_futari.h + .spv dumps.
    // -------------------------------------------------------------
    std::sort(matched.begin(), matched.end(), [](const MatchedShader& a, const MatchedShader& b) {
        return a.guestAddr < b.guestAddr;
    });

    std::ostringstream out;
    out << "// Auto-generated by render/tools/extract_cache.cpp. DO NOT EDIT BY HAND.\n";
    out << "// Decoded from XenosRecomp shader cache (shaders/shader_cache_shell.h) cross-referenced\n";
    out << "// against guest memory captures caps_s8/cap_image.bin (0x82000000) and cap_gimage.bin (0x88000000).\n";
    out << "//\n";
    out << "// Cache entries: " << g_shaderCacheEntryCount << ", matched containers: " << matched.size() << "\n";
    out << "#pragma once\n\n";

    out << "typedef struct { int reg; unsigned v[4]; } FutariDef; // v = float bit patterns\n\n";
    out << "typedef struct\n{\n"
           "    unsigned long long guest_addr;\n"
           "    int is_pixel;\n"
           "    unsigned ucode_size;\n"
           "    unsigned char ucode_prefix[32];\n"
           "    unsigned spec_mask;\n"
           "    const unsigned* spirv;\n"
           "    unsigned spirv_dwords;\n"
           "    const FutariDef* defs;\n"
           "    unsigned def_count;\n"
           "} FutariShader;\n\n";

    // Emit one SPIR-V array per unique cache entry that was actually matched
    // by at least one container (keeps the header minimal).
    std::vector<int> entryArrayEmitted(g_shaderCacheEntryCount, -1);
    for (const auto& ms : matched)
        entryArrayEmitted[ms.entryIndex] = 1;

    for (size_t i = 0; i < g_shaderCacheEntryCount; i++)
    {
        if (entryArrayEmitted[i] < 0)
            continue;

        const auto& spirv = entrySpirv[i];
        out << "static const unsigned g_futari_spirv_" << i << "[" << spirv.size() << "] = {\n";
        out << "\t";
        for (size_t w = 0; w < spirv.size(); w++)
        {
            char buf[16];
            snprintf(buf, sizeof(buf), "0x%08Xu,", spirv[w]);
            out << buf;
            if ((w % 8) == 7)
                out << "\n\t";
        }
        out << "\n};\n\n";
    }

    // Per-shader definition-table constants (baked; c255 etc. — shader-embedded, never in PM4).
    std::vector<std::vector<EmitDef>> allDefs(matched.size());
    for (size_t si = 0; si < matched.size(); si++)
    {
        allDefs[si] = parseDefs(matched[si].containerBase, readBE32(matched[si].containerBase + 4), matched[si].isPixel);
        if (!allDefs[si].empty())
        {
            out << "static const FutariDef g_futari_defs_" << si << "[" << allDefs[si].size() << "] = {";
            for (const auto& e : allDefs[si])
            {
                char buf[96];
                snprintf(buf, sizeof(buf), "{%d,{0x%Xu,0x%Xu,0x%Xu,0x%Xu}},", e.reg, e.v[0], e.v[1], e.v[2], e.v[3]);
                out << buf;
            }
            out << "};\n";
        }
    }
    out << "\n";

    out << "static const FutariShader g_futari_shaders[" << matched.size() << "] = {\n";
    for (size_t si = 0; si < matched.size(); si++)
    {
        const auto& ms = matched[si];
        const ShaderCacheEntry& e = g_shaderCacheEntries[ms.entryIndex];
        out << "\t{ 0x" << std::hex << ms.guestAddr << std::dec << "ULL, "
            << (ms.isPixel ? 1 : 0) << ", "
            << ms.ucodeSize << "u, { ";
        for (int b = 0; b < 32; b++)
        {
            char buf[8];
            snprintf(buf, sizeof(buf), "0x%02X,", ms.ucodePrefix[b]);
            out << buf;
        }
        out << " }, " << e.specConstantsMask << "u, "
            << "g_futari_spirv_" << ms.entryIndex << ", "
            << entrySpirv[ms.entryIndex].size() << "u, "
            << (allDefs[si].empty() ? std::string("0") : ("g_futari_defs_" + std::to_string(si))) << ", "
            << allDefs[si].size() << "u },\n";
    }
    out << "};\n\n";
    out << "static const unsigned g_futari_shader_count = " << matched.size() << "u;\n";

    {
        std::ofstream hf(outHeaderPath, std::ios::binary);
        if (!hf)
        {
            fprintf(stderr, "failed to open %s for writing\n", outHeaderPath);
            return 1;
        }
        std::string s = out.str();
        hf.write(s.data(), static_cast<std::streamsize>(s.size()));
    }

    // .spv dumps
    for (const auto& ms : matched)
    {
        const auto& spirv = entrySpirv[ms.entryIndex];
        char nameBuf[256];
        snprintf(nameBuf, sizeof(nameBuf), "%s/%s_%llX.spv", outSpvDir,
            ms.isPixel ? "ps" : "vs", (unsigned long long)ms.guestAddr);
        std::ofstream sf(nameBuf, std::ios::binary);
        if (sf)
            sf.write(reinterpret_cast<const char*>(spirv.data()),
                static_cast<std::streamsize>(spirv.size() * sizeof(uint32_t)));
    }

    printf("\n== Output ==\n");
    printf("header: %s\n", outHeaderPath);
    printf("spv dumps: %zu files under %s\n", matched.size(), outSpvDir);

    printf("\n%s\n", exitCode == 0 ? "ALL CHECKS PASSED" : "SOME CHECKS FAILED");
    return exitCode;
}
