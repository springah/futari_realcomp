#!/bin/bash
# build_win_abn.sh — NATIVE WINDOWS build of futari_merged_v154hi.exe:
#   the SAME host layer (shell + decomp + merged_xex + renderer) linked against the
#   reco_abnormal static recompilation in out_reco_abn/ instead of reco_normal's out_reco/.
#   reco_abnormal.xex = Ver 1.5 "Xbox 360 mode" / MODULE_154_3_HI / modeIdx 1.
#
# Variant of ../build_win.sh (which is UNTOUCHED and still builds build/futari_merged.exe).
# Differences, all of them:
#   * GAME tree            out_reco/*.cpp            -> out_reco_abn/*.cpp
#   * include path         -I out_reco               -> -I out_reco_abn      (game AND shell)
#   * forced include       out_reco/rt_indirect.h    -> out_reco_abn/rt_indirect.h
#   * object dir           build/obj_win/                  -> build/obj_win_abn/
#   * output               build/futari_merged.exe         -> futari_merged_v154hi.exe
#   * forced include       + out_reco_abn/abn_symbol_map.h on the HOST hook TUs only (see below)
#   * -D                   + GA_DSHIFT=0x60u on the 4 shared TUs that read load-bearing guest
#                            .data addresses (merged_xex, shell/gen/rt.cpp, shell/gen/stubs.cpp,
#                            render/vk_render.cpp).  Default 0 => normal build unaffected.
#   * omitted TU           decomp/game/game_entry_msgs.cpp (the C1 MATCHED GameEntry) — see below
#
# ★ HOOK REVIVAL (2026-07-30, _tmpscripts/abn_hooks_revive_notes.md).  The host layer names
#   reco_NORMAL guest addresses.  out_reco_abn/abn_symbol_map.h (GENERATED by
#   out_reco_abn/tools_abn/gen_symbol_map.py) #defines every shifted symbol onto its +8 twin,
#   both `sub_X` and `__imp__sub_X`.  It is force-included ONLY onto:
#       out_reco/merged/merged_xex.cpp   (76 shifted hook symbols -> 152 #defines)
#       decomp/*/*.cpp EXCEPT game_entry_msgs.cpp
#   It is deliberately NOT included onto the out_reco_abn generated tree (those files already use
#   abn names; renaming them would double-shift) nor onto shell/gen/* or render/* (zero 0x88
#   function-symbol references — comments only).
#
#   decomp/game/game_entry_msgs.cpp IS EXCLUDED FROM THE ABN BUILD ENTIRELY (not compiled, not
#   linked).  It is the C1 MATCHED GameEntry translation and its body stores to reco_normal .data
#   literals (0x887AD547, 0x887AD58C, 0x887AD5CC, ...) which move +0x60 in reco_abnormal, so
#   renaming it onto 0x8824E6A0 would ship subtly-wrong stores.  In the abn build the GENERATED
#   body owns __imp__sub_8824E6A0 and merged_xex.cpp's renamed [gemsg]/[msglog] wrapper owns the
#   strong sub_8824E6A0 -> instruments alive on the generated body.  The MATCHED status must be
#   re-earned at 0x8824E6A0 before that TU can come back.
#
# NOTHING in ../build_win.sh is modified.  The four shared TUs gained only default-neutral
# #ifndef GA_DSHIFT blocks (proved: -S assembly of each is identical pre/post, modulo clang's
# anonymous-namespace content hash in vk_render.cpp).
#
# CENSUS MODE:  ABN_NOSTUBS=1 bash _tmpscripts/build_win_abn.sh
#   omits abn_hook_stubs.o so the link surfaces the raw unresolved-__imp__ list.  Post-revival
#   that list is EMPTY, which is the point: the stub TU is no longer needed.
#
# Run from git-bash.  cwd-independent: cds to xr-work.
set -u
cd "$(dirname "$0")"   # 2026-08-07: promoted from _tmpscripts/ to the repo root
mkdir -p build
CXX="/c/Program Files/LLVM/bin/clang++.exe"
DERISK="external/xr-derisk"
OUT="out_reco_abn"
EXE="futari_merged_v154hi.exe"
OBJ="build/obj_win_abn"
VKSDK=$(ls -d /c/VulkanSDK/*/ 2>/dev/null | sort -V | tail -1)   # newest installed Vulkan SDK
# -DFUTARI_MODULE=1 selects the reco_abnormal descriptor in host/futari_module_desc.h (L3/E4 of
# _tmpscripts/dll_packaging_plan.md).  It REPLACES -DGAME_ENTRY_ORD1_VAL and
# -DGAME_MODULE_BASENAME_STR (both now #error'd in merged_bridge.cpp if still defined) and will
# replace -DGA_DSHIFT as the GA_* macros migrate into the descriptor.  It is in STD — on EVERY
# TU — on purpose: the old flags were sprayed onto a hand-picked subset, so a TU that grew a use
# of one of them silently compiled reco_NORMAL's constants.  See build_win.sh's twin comment.
# FUTARI_BUILD_ID: twin of build_win.sh's. Without it this arm's [env] banner printed build=unknown
# — and this is the exe the XBOX 360 launcher runs, so the arm most likely to be deployed stale was
# also the one that could not name itself. Same wrong-attribution class the banner exists to kill.
BUILD_ID="$(git rev-parse --short HEAD 2>/dev/null || echo nogit)$(git diff --quiet 2>/dev/null || echo -dirty)"
STD="--target=x86_64-pc-windows-msvc -std=c++20 -O2 -D_CRT_SECURE_NO_WARNINGS -Wno-macro-redefined -DFUTARI_MODULE=1 -DFUTARI_BUILD_ID=\"$BUILD_ID\""
GAME_INC="-I $OUT -I $DERISK/XenonUtils -I $DERISK/thirdparty/simde"
SHELL_INC="-I shell/gen -I $OUT -I $DERISK/thirdparty/simde"
XS="-D_xstart=_xstart_shell -D__imp___xstart=__imp___xstart_shell"
RT="-include $OUT/rt_indirect.h"
MAP="-include $OUT/abn_symbol_map.h"          # +8 hook rename (HOST TUs ONLY — see header)
DSHIFT="-DGA_DSHIFT=0x60u"                    # guest .data +0x60 law — NOW render/vk_render.cpp ONLY.
# ★ L3/E4: the other five consumers (merged_{game,bridge,shell}, shell/gen/{rt,stubs}.cpp) read the
#   six load-bearing addresses out of host/futari_module_desc.h, selected by -DFUTARI_MODULE=1 in
#   STD, so GA_DSHIFT no longer reaches them.  PROVEN, not assumed: recompiling those five WITHOUT
#   this flag yields byte-identical -S (_tmpscripts/l3_baseline/s4f_nodshift_probe vs s4f_asset_commit).
#   vk_render.cpp was owned by another session during L3 and still computes GA_FIELD_ACTIVE as
#   (0x885C1A20u + GA_DSHIFT) — it is THE one remaining un-descriptorised consumer and the one TU
#   where dropping this flag would silently address reco_normal .data.  Folding it in is the
#   documented L3 follow-up (_tmpscripts/l3_descriptorise_notes.md).

# DECOMP_DIR: readable-decomp tree, now the sibling repo projects/futari_decomp (2026-08-14
# split). Exported so gen_symbol_map.py sees the same override; defined BEFORE the map regen.
export DECOMP_DIR="${DECOMP_DIR:-../futari_decomp/decomp}"

# Re-apply the two hand fixups XenonRecomp does not emit (idempotent; see the script).
python "$OUT/postregen_abn.py" || exit 1
# Regenerate the +8 symbol map from the census + the split rule (aborts loudly on any violation:
# census/rule disagreement, missing twin, or chained macro expansion).
python "$OUT/tools_abn/gen_symbol_map.py" || exit 1

mkdir -p "$OBJ"
rm -f "$OBJ"/*.o "$OBJ"/*.err
# r23-w38 (same guard as build_win_dll.sh): retire, do not delete — a failed link must not
# destroy the last good artifact.  $EXE absent still means "this run produced nothing".
[ -f "$EXE" ] && mv -f "$EXE" "$EXE.lastgood"

i=0
sem(){ i=$((i+1)); if [ $((i%12)) -eq 0 ]; then wait; fi; }
cc(){ # name  src  flags...
  local name="$1" src="$2"; shift 2
  ( "$CXX" $STD "$@" -c "$src" -o "$OBJ/$name.o" 2>"$OBJ/$name.err" || echo "FAILED: $name" ) &
  sem
}

echo "== DECOMP tree (decomp/*/*.cpp — campaign C1+; __imp__ overrides, linked FIRST) =="
echo "   +8 symbol map applied; the abn exclusion list is IN SYNC WITH build_win_dll.sh:334"
echo "   (bodies carry reco_normal .data literals that move +0x60 — see the script header)."
for f in "$DECOMP_DIR"/game/*.cpp "$DECOMP_DIR"/shell/*.cpp; do
  [ -f "$f" ] || continue
  n=$(basename "$f" .cpp)
  # abn-excluded: reco_normal .data literals move +0x60 (LAWS I3; the asset TUs joined
  # game_entry_msgs 2026-08-13 after the differential caught the abn pump dead).
  #
  # ★ r23-w43: SYNCED WITH build_win_dll.sh:334 (+13 TUs).  This list had drifted 13 TUs behind
  #   the DLL path — every factored TU promoted since w22 (objaction*, the fam* families,
  #   paperdoll2_draw, class233_236_draw, actor3pose_draw) was excluded there and NOT here, while
  #   this script still force-includes abn_symbol_map.h.  So the per-mode abn exe compiled those
  #   TUs, the +8 map renamed them onto their abn twins, and they RAN — reading and, for
  #   actor3pose_draw, WRITING un-shifted .data literals.  The +8 map renames FUNCTION symbols
  #   only; embedded DATA addresses are never translated.
  #   w39 ruled the drift STALE-BUT-IMMATERIAL on the premise that no leg runs these bodies in
  #   reco_abnormal.  ⚠ THAT PREMISE IS REFUTED: r23-w43 leg a3y43 measured 800 dispatches of
  #   sub_881A1430 on a live reco_abnormal arm (bank/r23/w43/a3y43_a3emit.txt).  The DLL path was
  #   always correct so nothing ever shipped broken, but the exe's immateriality argument is gone.
  #   ⚠ MATCHES ON TU BASENAME ($n = basename $f .cpp) — a TU renamed on promotion must have its
  #   new basename added HERE in the SAME change, or the exclusion silently does nothing.
  case "$n" in game_entry_msgs|asset_decode|asset_pump|archive|mem_util|asset_upload|page_bake\
|objaction|objaction_queue|objaction_queue2|bossvein_object|fam4_object|fam1_arms|fam3_arms\
|fam9_arms|fam10_arms|fam11_tick|paperdoll2_draw|class233_236_draw|actor3pose_draw) continue;; esac
  # -I . : decomp TUs reference host/render headers realcomp-root-relative (repo split).
  cc "decomp_$n" "$f" $GAME_INC -I . $RT $MAP
done
# decomp/game_abn/ = abn-NATIVE translations (addresses already +8/+0x60-resolved; the C1-class
# GameEntry re-earn TU). NO symbol map here — renaming abn-native names would double-shift.
# Deliberately a separate dir: build_win.sh globs decomp/game/*.cpp, so a TU there would leak
# into the NORMAL build (landmine found by the MATCHED-prep agent).
for f in "$DECOMP_DIR"/game_abn/*.cpp; do
  [ -f "$f" ] || continue
  n=$(basename "$f" .cpp)
  cc "decomp_$n" "$f" $GAME_INC -I . $RT
done

echo "== GAME tree ($OUT/*.cpp, minus shell_only_stubs and abn_hook_stubs) =="
for f in $OUT/*.cpp; do
  n=$(basename "$f" .cpp)
  [ "$n" = "shell_only_stubs" ] && continue
  [ "$n" = "abn_hook_stubs" ] && continue
  cc "game_$n" "$f" $GAME_INC $RT
done

echo "== SHELL guest tree (shell/gen/ppc_recomp.*.cpp) =="
for f in shell/gen/ppc_recomp.*.cpp; do
  n=$(basename "$f" .cpp); cc "shell_$n" "$f" $SHELL_INC $XS $RT
done
cc "shell_ppc_func_mapping" "shell/gen/ppc_func_mapping.cpp" $SHELL_INC $XS $RT -DPPCFuncMappings=PPCFuncMappings_shell

echo "== SHELL kernel (real vblank/notify/signin/D3D9 layer) =="
cc "shellkernel_rt"    "shell/gen/rt.cpp"    $SHELL_INC $XS $RT
cc "shellkernel_stubs" "shell/gen/stubs.cpp" $SHELL_INC $XS $RT
cc "shellkernel_rt_audio" "shell/gen/rt_audio.cpp" -Ithirdparty/sdl3/include
cc "shellkernel_rt_xwma"  "shell/gen/rt_xwma.cpp"

echo "== Gate-2 bridge (merged_xex 3-way split — SHARED TUs, abn constants via -D + +8 map) =="
# L2 split (_tmpscripts/dll_packaging_plan.md §2.3, notes in _tmpscripts/l2_split_notes.md).
# WHICH TU GETS WHICH FLAG — measured, not guessed (_tmpscripts/l2_flags.py):
#   $MAP  (-include abn_symbol_map.h)  -> merged_game.cpp ONLY.  All 85 shifted symbols the map
#         renames are named exclusively from sub_88 hook blocks, i.e. the game half.  Applying it
#         to merged_bridge/merged_shell is a provable no-op (gate: preprocess-with/without diff is
#         empty, _tmpscripts/l2_gate_map_noop.sh) — so it is left off, and a future sub_88
#         reference appearing in the shell/bridge half becomes a LOUD unresolved __imp__ instead
#         of a silent miss.
#   $DSHIFT (-DGA_DSHIFT=0x60u)        -> RETIRED FROM ALL THREE at L3 (descriptor).  Was: ALL THREE,
#         because every GA_* use site is in the game
#         half, but GA_DSHIFT defaults to 0u inside merged_common.h, so a TU that gains a GA_* use
#         without the flag would silently address reco_normal .data.  Passing it everywhere is
#         free and removes that class (same fragility rt.cpp still has — plan §2.2b).
#   -DGAME_ENTRY_ORD1_VAL / -DGAME_MODULE_BASENAME_STR  RETIRED AT L3.  Both values live in
#         host/futari_module_desc.h's reco_abnormal descriptor, selected by the -DFUTARI_MODULE=1
#         in STD above.  merged_bridge.cpp #error's if either macro is still defined, so a stale
#         flag cannot come back silently.
cc "merged_game"   "out_reco/merged/merged_game.cpp"   $GAME_INC $RT $MAP
cc "merged_bridge" "out_reco/merged/merged_bridge.cpp" $GAME_INC $RT
cc "merged_shell"  "out_reco/merged/merged_shell.cpp"  $GAME_INC $RT

echo "== Vulkan renderer (vk_render, RT_VK-gated) =="
cc "vk_render" "render/vk_render.cpp" -I "${VKSDK}Include" $DSHIFT

if [ "${ABN_NOSTUBS:-0}" = "1" ]; then
  echo "== abn hook stubs: SKIPPED (ABN_NOSTUBS=1 — census mode, link is EXPECTED to fail) =="
  STUBOBJ=""
else
  echo "== abn hook stubs (NOW EMPTY — abn_symbol_map.h resolved all 85; regenerate with tools_abn/gen_stubs.py) =="
  cc "abn_hook_stubs" "$OUT/abn_hook_stubs.cpp" $GAME_INC $RT
  STUBOBJ="$OBJ/abn_hook_stubs.o"
fi

wait
NOBJ=$(ls "$OBJ"/*.o 2>/dev/null | wc -l)
echo "objects: $NOBJ"
FAILED=0
for e in "$OBJ"/*.err; do if grep -q ' error' "$e" 2>/dev/null || grep -q 'error:' "$e" 2>/dev/null; then echo "--- $e ---"; grep -A2 'error' "$e" | head -12; FAILED=1; fi; done
if [ "$FAILED" -ne 0 ]; then echo "COMPILE_INCOMPLETE"; exit 1; fi

echo "== LINK (lld-link /FORCE:MULTIPLE, game+merged first) =="
"$CXX" --target=x86_64-pc-windows-msvc -fuse-ld=lld -O2 -std=c++20 \
  $(ls "$OBJ"/decomp_*.o 2>/dev/null) "$OBJ"/game_*.o "$OBJ"/merged_game.o "$OBJ"/merged_bridge.o "$OBJ"/merged_shell.o $STUBOBJ "$OBJ"/vk_render.o "$OBJ"/shell_*.o "$OBJ"/shellkernel_*.o \
  -o "$EXE" \
  "$DERISK/build-win/XenonUtils/XenonUtils.lib" \
  "$DERISK/build-win/XenonAnalyse/LibXenonAnalyse.lib" \
  "$DERISK/build-win/thirdparty/disasm/disasm.lib" \
  "$DERISK/build-win/thirdparty/xxHash/cmake_unofficial/xxhash.lib" \
  "$DERISK/build-win/thirdparty/fmt/fmt.lib" \
  "${VKSDK}Lib/vulkan-1.lib" \
  thirdparty/sdl3/lib/SDL3-static.lib -luser32 -lole32 -lwinmm -limm32 -loleaut32 -lversion -ladvapi32 -lsetupapi -lshell32 -lgdi32 -luuid \
  -Xlinker /FORCE:MULTIPLE -Xlinker /errorlimit:0 \
  2>"$OBJ"/link.err && echo "LINK_OK -> $EXE" || {
    echo "LINK_FAILED"
    # NOTE: lld-link prints __imp__sub_X as `__declspec(dllimport) _sub_X`, NOT as the raw
    # `__imp__sub_X` mangling -- grepping for `__imp__` finds nothing.  Match the dllimport form.
    echo "--- unresolved __imp__sub_88XXXXXX (the reco_abnormal port-cost census) ---"
    grep -o 'dllimport) _sub_88[0-9A-Fa-f]*' "$OBJ"/link.err | sed 's/.*_sub_/__imp__sub_/' | sort -u
    echo "--- count: $(grep -o 'dllimport) _sub_88[0-9A-Fa-f]*' "$OBJ"/link.err | sort -u | wc -l) distinct ---"
    echo "--- other unresolved (non-guest symbols) ---"
    grep 'undefined symbol' "$OBJ"/link.err | grep -v 'dllimport) _sub_88' | sort -u | head -30
    tail -20 "$OBJ"/link.err
    exit 1
  }
