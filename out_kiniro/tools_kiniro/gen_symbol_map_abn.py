#!/usr/bin/env python3
"""gen_symbol_map_abn.py -- kiniro_abnormal (Black Label XBOX 360 MODE, modeIdx 5) symbol map by the +8 LAW
(docs/PLAN_kiniro_bringup.md section 4 / step 4c).

kiniro_abnormal is kiniro_normal with one 2-instruction insertion in sub_880E1B68: every function start at or below
0x880E1B68 keeps its address, every start at or above 0x880E1C60 moves +8. So the reco_normal -> kiniro_abnormal map
is the reco_normal -> kiniro_normal map (out_kiniro/kiniro_symbol_map.h, body-matched with a positive control)
composed with that law. Nothing is matched again here; a target inside the split window, or a target that is not a
kiniro_abnormal function symbol, is an error, never a guess.

Writes
  out_kiniro_abn/kiniro_abn_symbol_map.h   the -include header for build_mac_dll.sh's kiniro_abn arm (modeIdx 5)
  out_kiniro_abn/kiniro_hook_stubs.cpp     a copy of out_kiniro's (the dropped set and its names are identical)
and prints the law's own control: how many kiniro_normal function starts land on a kiniro_abnormal function start.

    python3 out_kiniro/tools_kiniro/gen_symbol_map_abn.py [--check]
"""
import os, re, sys, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
KIN = os.path.join(REPO, "out_kiniro"); ABN = os.path.join(REPO, "out_kiniro_abn")
SPLIT_LO, SPLIT_HI = 0x880E1B68, 0x880E1C60

def law(a):
    if a <= SPLIT_LO: return a
    if a >= SPLIT_HI: return a + 8
    raise SystemExit("0x%08X lies inside the +8 split window (0x%08X, 0x%08X): no law for it" % (a, SPLIT_LO, SPLIT_HI))

def syms(shared_h):
    s = open(shared_h, encoding="utf-8").read()
    return set(int(h, 16) for h in re.findall(r"PPC_EXTERN_FUNC\(sub_([0-9A-Fa-f]{8})\)", s))

def starts(mapping_cpp):
    s = open(mapping_cpp, encoding="utf-8", errors="replace").read()
    return sorted(set(int(x, 16) for x in re.findall(r"\{\s*0x([0-9A-Fa-f]{8}),\s*sub_", s)))

def main():
    check = "--check" in sys.argv
    kin_syms, abn_syms = syms(os.path.join(KIN, "ppc_recomp_shared.h")), syms(os.path.join(ABN, "ppc_recomp_shared.h"))
    # the law's own control over every kiniro_normal function start
    ks, as_ = starts(os.path.join(KIN, "ppc_func_mapping.cpp")), set(starts(os.path.join(ABN, "ppc_func_mapping.cpp")))
    held = sum(1 for a in ks if (law(a) if not (SPLIT_LO < a < SPLIT_HI) else None) in as_)
    inwin = [a for a in ks if SPLIT_LO < a < SPLIT_HI]
    print("+8 law over kiniro_normal function starts: %d/%d land on a kiniro_abnormal start; %d start(s) inside the split window: %s"
          % (held, len(ks), len(inwin), " ".join("0x%08X" % a for a in inwin)))
    src = open(os.path.join(KIN, "kiniro_symbol_map.h"), encoding="utf-8").read().split("\n")
    out = []; n_ren = n_same = n_drop = 0; seen = set()
    out.append("// kiniro_abn_symbol_map.h - GENERATED by out_kiniro/tools_kiniro/gen_symbol_map_abn.py.  DO NOT EDIT.")
    out.append("//")
    out.append("// reco_normal -> kiniro_abnormal (Black Label XBOX 360 MODE, modeIdx 5) = out_kiniro/kiniro_symbol_map.h composed")
    out.append("// with the +8 law (PLAN_kiniro_bringup section 4): targets at or below 0x%08X keep their address, targets at or" % SPLIT_LO)
    out.append("// above 0x%08X move +8. Force-included by build_mac_dll.sh's kiniro_abn arm ONLY (merged_game.cpp + nvk_game_hooks.cpp)." % SPLIT_HI)
    out.append("// DROPPED symbols are the same set as kiniro_normal's (sub_X_KDROP, out_kiniro_abn/kiniro_hook_stubs.cpp).")
    out.append("#pragma once"); out.append("#include <cstdint>"); out.append("struct PPCContext;"); out.append("")
    i = 0
    while i < len(src):
        l = src[i]
        m = re.match(r"#define\s+(sub_[0-9A-F]{8})\s+(sub_[0-9A-F]{8})_KDROP\s*(//.*)?$", l)
        if m:   # dropped: copy the 4-line block verbatim
            out.extend(src[i:i+4]); n_drop += 1; seen.add(m.group(1)); i += 4; continue
        m = re.match(r"#define\s+(sub_[0-9A-F]{8})\s+(sub_[0-9A-F]{8})\s*(//.*)?$", l)
        if m:   # renamed in kiniro_normal: compose
            a, t = m.group(1), int(m.group(2)[4:], 16); t2 = law(t)
            if t2 not in abn_syms: raise SystemExit("%s -> kiniro 0x%08X -> abn 0x%08X is not a kiniro_abnormal symbol" % (a, t, t2))
            out.append("#define %-20s sub_%08X         %s" % (a, t2, (m.group(3) or "//") + "  [abn: kiniro 0x%08X %+d]" % (t, t2 - t)))
            out.append("#define __imp__%-13s __imp__sub_%08X" % (a, t2)); n_ren += 1; seen.add(a); i += 2; continue
        m = re.match(r"//\s+(sub_[0-9A-F]{8})\s+same address\s+(\[[^\]]+\].*)$", l)
        if m:   # same address in kiniro_normal: the law decides whether abn needs a rename
            a = m.group(1); t = int(a[4:], 16); t2 = law(t)
            if t2 not in abn_syms: raise SystemExit("%s (same address in kiniro) -> abn 0x%08X is not a kiniro_abnormal symbol" % (a, t2))
            if t2 == t: out.append("//   %s  same address  %s" % (a, m.group(2))); n_same += 1
            else:
                out.append("#define %-20s sub_%08X         // +8 (same address in kiniro_normal) %s" % (a, t2, m.group(2)))
                out.append("#define __imp__%-13s __imp__sub_%08X" % (a, t2)); n_ren += 1
            seen.add(a); i += 1; continue
        if l.startswith("// ----") or l.strip() == "": out.append(l)
        i += 1
    hdr = "// %d renamed, %d at the same address, %d DROPPED (%d symbols)." % (n_ren, n_same, n_drop, len(seen))
    out.insert(6, hdr)
    text = "\n".join(out).rstrip("\n") + "\n"
    dst = os.path.join(ABN, "kiniro_abn_symbol_map.h")
    if check:
        cur = open(dst, encoding="utf-8").read() if os.path.exists(dst) else ""
        print("CHECK:", "up to date" if cur == text else "STALE"); return 0 if cur == text else 1
    open(dst, "w", encoding="utf-8", newline="\n").write(text)
    shutil.copyfile(os.path.join(KIN, "kiniro_hook_stubs.cpp"), os.path.join(ABN, "kiniro_hook_stubs.cpp"))
    print("wrote %s (%s) and copied kiniro_hook_stubs.cpp" % (dst, hdr[3:]))
    return 0

if __name__ == "__main__":
    sys.exit(main())
